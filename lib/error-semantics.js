export function httpStatusForError(error) {
  if (Number.isInteger(error?.status)) return error.status;
  const code = String(error?.code ?? '');
  if (BAD_REQUEST_CODES.has(code)) return 400;
  if (PAYLOAD_TOO_LARGE_CODES.has(code)) return 413;
  if (NOT_FOUND_CODES.has(code)) return 404;
  if (CONFLICT_CODES.has(code)) return 409;
  if (SERVICE_UNAVAILABLE_CODES.has(code)) return 503;
  return 500;
}

export function cliExitCodeForError(error) {
  const code = String(error?.code ?? '');
  if (code === 'SECRET_DETECTED') return 3;
  if (code === 'ENOENT') return 127;
  if (BAD_REQUEST_CODES.has(code) || PAYLOAD_TOO_LARGE_CODES.has(code) ||
      CLI_USAGE_CONFLICT_CODES.has(code) || CLI_INPUT_NOT_FOUND_CODES.has(code)) {
    return 2;
  }
  return 1;
}

// Every code the product throws should land in one of the sets above; anything
// missing silently becomes HTTP 500 and CLI exit 1. Exported so a test can hold
// the taxonomy to the code actually thrown in lib/.
export const REGISTERED_ERROR_CODES = Object.freeze([...new Set([
  ...BAD_REQUEST_CODES,
  ...PAYLOAD_TOO_LARGE_CODES,
  ...NOT_FOUND_CODES,
  ...CONFLICT_CODES,
  ...SERVICE_UNAVAILABLE_CODES,
  ...CLI_USAGE_CONFLICT_CODES,
  ...CLI_INPUT_NOT_FOUND_CODES,
  ...INTERNAL_FAILURE_CODES
])].sort());
